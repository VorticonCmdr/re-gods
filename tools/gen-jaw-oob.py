#!/usr/bin/env python3
"""gen-jaw-oob.py — src/game/guardian-jaw-oob.js from GAME.EXE.

World 2's jaw (CS:0xD115) reads SS:[0x57D0 + 4*[0x2F0]] as {sprite offset,
dy} words, masking [0x2F0] to 0..3 only on the ticks it steps it. World 4's
rise (CS:0xCBCB) leaves [0x2F0] = its base y, an even value 0xB0..0x180, so
a later world-2 fight can read past the 4-entry table into Table 2's
filename records. SS's image is GAME.EXE at file offset SS + 0x1F560
(checked: SS:0x5020, 0x537A and this whole range equal live memory).
"""
import struct, pathlib
here = pathlib.Path(__file__).resolve().parent
d = (here.parent / 'game' / 'GAME.EXE').read_bytes()
rows = []
for y in range(0xB0, 0x182, 2):
    off, dy = struct.unpack_from('<2h', d, 0x57D0 + 4 * y + 0x1F560)
    rows.append(f'  [0x{y:x}, [{off}, {dy}]],')
out = ('/* guardian-jaw-oob.js — GENERATED by tools/gen-jaw-oob.py from GAME.EXE.\n'
       ' * Do not edit by hand. SS:0x57D0 + 4*v for the [0x2F0] values world 4\'s\n'
       ' * rise can leave (even, 0xB0..0x180): [sprite offset, dy], signed. */\n'
       'export const W2_JAW_OOB = new Map([\n' + '\n'.join(rows) + '\n]);\n')
(here.parent / 'src' / 'game' / 'guardian-jaw-oob.js').write_text(out)
print(len(rows), 'entries')
