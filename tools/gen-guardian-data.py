#!/usr/bin/env python3
"""gen-guardian-data.py — write src/game/guardian-data.js from live memory.

The guardian scripts live in GAME.EXE's stack/data segment (SS-relative,
read with `mov si,[0x292] / mov cl,[ss:si]`), which the port does not
stage. They are read here from a running DOSBox (REST API, localhost:8386,
live SS = 0x22AA) rather than transcribed by hand: two-byte steps
(frame, signed dx) up to the first byte with bit 7 set.

  python3 tools/gen-guardian-data.py
"""
import urllib.request

SS = 0x22AA
SCRIPTS = {  # name: (SS offset, where the world entry installs it)
    'W1_SCRIPT': (0x53C2, 'CS:0xC4FB mov ax,0x53c2 / [0x292]; loop target CS:0xD89F'),
}


def read(off, n):
    return urllib.request.urlopen(f'http://localhost:8386/api/v1/memory/{SS}/{off}/{n}').read()


out = ['/* guardian-data.js — GENERATED by tools/gen-guardian-data.py from live',
       ' * DOSBox memory (SS:0x22AA). Do not edit by hand. Each step is',
       ' * [frame, dx]: the driver reads one step every other tick. */', '']
for name, (off, cite) in SCRIPTS.items():
    d = read(off, 512)
    steps, i = [], 0
    while not d[i] & 0x80:
        dx = d[i + 1] - 256 if d[i + 1] > 127 else d[i + 1]
        steps.append(f'[{d[i]},{dx}]')
        i += 2
    out.append(f'/** SS:0x{off:04X}, {len(steps)} steps, terminator 0x{d[i]:02X} at +{i}. {cite} */')
    out.append(f'export const {name} = Object.freeze([')
    for k in range(0, len(steps), 12):
        out.append('  ' + ','.join(steps[k:k + 12]) + ',')
    out.append(']);')
    out.append('')
# World 3 (CS:0xC545 [0x292] := 0x5468): 3-byte records (frame, dx, dy);
# frame bytes >= 0x80 are commands (0xFD lift, 0xFE x-test). Kept as raw
# bytes, because the x-test rewinds the pointer by 0x5D bytes (CS:0xD801).
W3_OFF = 0x5468
d = read(W3_OFF, 1024)
i = 0
while d[i] != 0xFF:
    i += 3
w3 = d[:i + 1]
out.append(f'/** SS:0x{W3_OFF:04X}, {i // 3} records of 3 bytes, terminator 0xFF at +{i}. '
           'CS:0xC545; interpreted by CS:0xD778-0xD83E. */')
out.append('export const W3_SCRIPT = Uint8Array.from([')
for k in range(0, len(w3), 24):
    out.append('  ' + ','.join(str(v) for v in w3[k:k + 24]) + ',')
out.append(']);')
out.append('')
open(__file__.rsplit('/', 2)[0] + '/src/game/guardian-data.js', 'w').write('\n'.join(out))
print('wrote', len(SCRIPTS), 'scripts')
